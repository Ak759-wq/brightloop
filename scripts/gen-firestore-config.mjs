// Embeds firestore.rules + firestore.indexes.json into a TS module so the
// /api/admin/setup-firestore route can deploy them from Vercel without firebase-tools.
import { readFileSync, writeFileSync } from "node:fs";
const rules = readFileSync("firestore.rules", "utf8");
const indexes = JSON.parse(readFileSync("firestore.indexes.json", "utf8"));
writeFileSync(
  "src/server/generated/firestoreConfig.ts",
  `// AUTO-GENERATED by scripts/gen-firestore-config.mjs – do not edit.\n` +
    `export const FIRESTORE_RULES = ${JSON.stringify(rules)};\n` +
    `export const FIRESTORE_INDEXES = ${JSON.stringify(indexes, null, 2)} as const;\n`
);
console.log("firestoreConfig.ts generated");
